#!/usr/bin/env python3
"""Generate portable C17 COM shim headers for Monac from MinGW-w64 SDK headers.

Generates:
    src/platform/d2d_c.h         Direct2D 1.0 flat vtables
    src/platform/dwrite_c.h      DirectWrite types + flat vtables
    src/platform/iids_gen.h      IIDs / CLSIDs needed by Monac and Demos
    tools/shim_manifest.txt      Ordered interface method baseline
    tests/shim_layout_checks.h   Compile-time vtable size/offset assertions (MinGW)
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shimparse as sp  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_INC = r"F:\_\mingw\x86_64-w64-mingw32\include"

BANNER = (
    "/* AUTO-GENERATED by tools/gen_com_shim.py -- do not edit by hand.\n"
    " * Regenerate with: python tools/gen_com_shim.py\n"
    " * Source of truth: MinGW-w64 C-mode SDK headers; layout verified at\n"
    " * compile time by tests/test_shim_layout.c (MinGW).\n"
    " */\n"
)

KEEP_TOKENS = {"IID", "REFIID", "REFGUID", "REFCLSID"}
TOKEN_ALIASES = {"WINBOOL": "BOOL"}

# Direct2D COM methods returning structs by value follow MSVC C++ member-function
# ABI (hidden out-pointer right after `This`, returning that pointer), which
# differs from C struct-return ABI on both MinGW-w64 and MSVC in C mode.
AGGREGATE_RETURN_TYPES = {
    "D2D1_SIZE_F",
    "D2D1_SIZE_U",
    "D2D1_PIXEL_FORMAT",
    "D2D1_COLOR_F",
    "D2D1_POINT_2F",
}

DWRITE_TYPED = {
    "QueryInterface", "AddRef", "Release",
    "GetSystemFontCollection",
    "CreateTextFormat", "CreateTextLayout", "CreateGdiCompatibleTextLayout",
    "CreateEllipsisTrimmingSign",
    "SetTextAlignment", "SetParagraphAlignment", "SetWordWrapping",
    "SetReadingDirection", "SetFlowDirection",
    "SetIncrementalTabStop", "SetTrimming", "SetLineSpacing",
    "GetTextAlignment", "GetParagraphAlignment", "GetWordWrapping",
    "GetIncrementalTabStop", "GetLineSpacing",
    "GetFontSize", "GetFontWeight", "GetFontStyle", "GetFontStretch",
    "SetMaxWidth", "SetMaxHeight",
    "SetFontFamilyName", "SetFontWeight", "SetFontStyle", "SetFontStretch",
    "SetFontSize", "SetUnderline", "SetStrikethrough",
    "SetDrawingEffect", "SetInlineObject",
    "GetMaxWidth", "GetMaxHeight",
    "Draw", "GetLineMetrics", "GetMetrics", "GetOverhangMetrics",
    "GetClusterMetrics", "DetermineMinWidth",
    "HitTestPoint", "HitTestTextPosition", "HitTestTextRange",
    "GetBreakConditions",
    "IsPixelSnappingDisabled", "GetCurrentTransform", "GetPixelsPerDip",
    "DrawGlyphRun", "DrawUnderline", "DrawStrikethrough", "DrawInlineObject",
    "GetFontFamilyCount", "GetFontFamily", "FindFamilyName",
}

RE_INTERFACE_TOKEN = re.compile(r"\b(?<!MC_)(I[A-Z][A-Za-z0-9_]*)\b")
RE_DWRITE_TYPE = re.compile(r"\bDWRITE_[A-Za-z0-9_]+\b")


def die(msg):
    print("error: " + msg, file=sys.stderr)
    sys.exit(1)


def warn(msg):
    print("warning: " + msg, file=sys.stderr)


def apply_aliases(text, hook=""):
    for src, dst in TOKEN_ALIASES.items():
        text = re.sub(r"\b%s\b" % src, dst, text)
    for unknown in re.findall(r"\bWIN[A-Z][A-Za-z0-9_]*\b", text):
        if unknown not in ("WINAPI", "WCHAR", "WIN32_FIND_DATAW"):
            warn("MinGW-only token %r kept in %s" % (unknown, hook or "types"))
    return text


def rewrite_types(text, owned, hook=""):
    def repl(m):
        name = m.group(1)
        if name in KEEP_TOKENS:
            return name
        if name in owned:
            return "MC_" + name
        if name in TOKEN_ALIASES:
            return TOKEN_ALIASES[name]
        if name.startswith(("ID2D1", "IDWrite", "IWIC", "IDXGI", "IStream", "IUnknown")):
            return "void"
        warn("unmapped interface-ish token %r in %s" % (name, hook))
        return "void"

    for src, dst in TOKEN_ALIASES.items():
        text = re.sub(r"\b%s\b" % src, dst, text)
    return RE_INTERFACE_TOKEN.sub(repl, text)


def normalise_decl(text):
    text = " ".join(text.split())
    text = re.sub(r"\s*\*\s*", " *", text)
    text = text.replace(" * *", " **")
    text = re.sub(r"\(\s+", "(", text)
    text = re.sub(r"\s+\)", ")", text)
    return text.strip()


def build_member(ret, name, args, field, typed, owned, hook):
    if not typed:
        return "    void *%s;" % field
    ret = normalise_decl(rewrite_types(ret, owned, hook))
    args = normalise_decl(rewrite_types(args, owned, hook))
    if ret in AGGREGATE_RETURN_TYPES:
        if "," in args:
            first, rest = args.split(",", 1)
            args = "%s, %s *out, %s" % (first.strip(), ret, rest.strip())
        else:
            args = "%s, %s *out" % (args.strip(), ret)
        ret = ret + " *"
    return "    %s (STDMETHODCALLTYPE *%s)(%s);" % (ret, field, args)


def emit_interface(name, methods, typed_pred, owned):
    lines = ["struct MC_%sVtbl {" % name]
    used = {}
    pairs = []
    for ret, mname, args, _static in methods:
        used[mname] = used.get(mname, 0) + 1
        field = mname if used[mname] == 1 else "%s_%d" % (mname, used[mname])
        lines.append(build_member(ret, mname, args, field,
                                  typed_pred(name, mname), owned,
                                  "%s::%s" % (name, mname)))
        pairs.append((mname, field))
    lines.append("};")
    return "\n".join(lines), pairs


def forward_decls(names):
    out = []
    for n in names:
        out.append("typedef struct MC_%s MC_%s;" % (n, n))
        out.append("typedef struct MC_%sVtbl MC_%sVtbl;" % (n, n))
    return "\n".join(out)


def object_structs(names):
    out = []
    for n in names:
        out.append("struct MC_%s { const MC_%sVtbl *lpVtbl; };" % (n, n))
    return "\n".join(out)


def index_dwrite_definitions(text):
    defs = {}
    members = {}
    for m in re.finditer(r"typedef\s+(enum|struct)\s+(\w+)\s*\{", text):
        kind, name = m.group(1), m.group(2)
        depth = 1
        i = m.end()
        while i < len(text) and depth:
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
            i += 1
        semi = text.find(";", i)
        src = text[m.start():semi + 1]
        defs[name] = (m.start(), semi + 1, src)
        if kind == "enum":
            for mem in re.finditer(r"\b([A-Z][A-Z0-9_]*)\b\s*(?:=[^,}]*)?[,}]", src):
                members[mem.group(1)] = name
    for m in re.finditer(r"typedef\s+([A-Za-z_][\w\s\*]*?)\s+(\w+)\s*;", text):
        name = m.group(2)
        if name.startswith("DWRITE_") and name not in defs:
            defs[name] = (m.start(), m.end(), text[m.start():m.end()])
    for m in re.finditer(r"^#define\s+(DWRITE_\w+)\s+([^\n]*)$", text, re.M):
        name = m.group(1)
        if name not in defs:
            defs[name] = (m.start(), m.end(), text[m.start():m.end()])
    return defs, members


def collect_dwrite_types(defs, members, seeds, external=()):
    external = set(external)
    needed = set()
    queue = list(seeds)
    missing = []
    while queue:
        name = queue.pop()
        if name in needed or name in external:
            continue
        entry = defs.get(name)
        if entry is None:
            owner = members.get(name)
            if owner is not None:
                if owner not in needed:
                    queue.append(owner)
                continue
            missing.append(name)
            continue
        needed.add(name)
        for tok in RE_DWRITE_TYPE.findall(entry[2]):
            if tok != name and tok not in needed:
                queue.append(tok)
    return needed, missing


RE_DEFINE_GUID = re.compile(
    r"DEFINE_GUID\(\s*([A-Za-z_]\w*)\s*,\s*([^;]*?)\)\s*;", re.S
)

EXTRA_GUID_SOURCES = [
    ("d2d1_1.h", [
        "IID_ID2D1DeviceContext",
    ]),
    ("d2d1_2.h", [
        "IID_ID2D1DeviceContext1",
    ]),
    ("dwrite_2.h", [
        "IID_IDWriteFactory2",
    ]),
    ("wincodec.h", [
        "CLSID_WICImagingFactory",
        "IID_IWICImagingFactory",
        "GUID_ContainerFormatPng",
        "GUID_WICPixelFormat32bppBGRA",
    ]),
]


def index_guids(text):
    out = {}
    for m in RE_DEFINE_GUID.finditer(text):
        out[m.group(1)] = normalise_decl(" ".join(m.group(2).split()))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mingw-include", default=DEFAULT_INC)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    inc = args.mingw_include
    d2d_path = os.path.join(inc, "d2d1.h")
    dwrite_path = os.path.join(inc, "dwrite.h")
    for p in (d2d_path, dwrite_path):
        if not os.path.isfile(p):
            die("missing %s" % p)

    d2d_raw = sp.load_header(d2d_path)
    dwrite_raw = sp.load_header(dwrite_path)

    blocks_d2d = sp.find_vtbl_blocks(d2d_raw)
    blocks_dw = sp.find_vtbl_blocks(dwrite_raw)

    d2d_tables = {}
    for name in sp.SEED_D2D:
        d2d_tables[name] = sp.collect_interface(blocks_d2d, name, warn)
    dwrite_tables = {}
    for name in sp.SEED_DWRITE:
        dwrite_tables[name] = sp.collect_interface(blocks_dw, name, warn)

    owned_d2d = set(d2d_tables)
    owned_dwrite = set(dwrite_tables)
    owned = owned_d2d | owned_dwrite | {"IUnknown"}

    # ---- d2d_c.h -------------------------------------------------------
    order_d2d = [n for n in sp.SEED_D2D if n != "IUnknown"]
    d2d_parts = [BANNER]
    d2d_parts.append(
        "#ifndef MONAC_PLATFORM_D2D_C_H\n#define MONAC_PLATFORM_D2D_C_H\n\n")
    d2d_parts.append('#include "com_base.h"\n')
    d2d_parts.append("#include <d2d1.h>\n")
    d2d_parts.append('#include "iids_gen.h"\n')
    d2d_parts.append('#include "dwrite_c.h"\n')
    d2d_parts.append("\n" + forward_decls(order_d2d) + "\n")
    d2d_parts.append("\n" + object_structs(order_d2d) + "\n")
    for name in order_d2d:
        text, _pairs = emit_interface(
            name, d2d_tables[name], lambda i, m: True, owned)
        d2d_parts.append("\n" + text + "\n")
    d2d_parts.append("\n#endif /* MONAC_PLATFORM_D2D_C_H */\n")
    d2d_text = "".join(d2d_parts)

    # ---- dwrite_c.h ----------------------------------------------------
    order_dw = [n for n in sp.SEED_DWRITE if n != "IUnknown"]
    seed_types = {
        "DWRITE_FACTORY_TYPE",
        "DWRITE_LINE_METRICS",
        "DWRITE_HIT_TEST_METRICS",
        "DWRITE_INLINE_OBJECT_METRICS",
        "DWRITE_OVERHANG_METRICS",
        "DWRITE_BREAK_CONDITION",
        "DWRITE_TEXT_METRICS",
        "DWRITE_CLUSTER_METRICS",
        "DWRITE_TEXT_RANGE",
        "DWRITE_TRIMMING",
        "DWRITE_MATRIX",
        "DWRITE_GLYPH_RUN",
        "DWRITE_GLYPH_RUN_DESCRIPTION",
        "DWRITE_UNDERLINE",
        "DWRITE_STRIKETHROUGH",
    }
    seed_types |= set(RE_DWRITE_TYPE.findall(d2d_text))
    for name in order_dw:
        for ret, mname, argtext, _s in dwrite_tables[name]:
            if mname in DWRITE_TYPED:
                seed_types |= set(RE_DWRITE_TYPE.findall(argtext))
                seed_types |= set(RE_DWRITE_TYPE.findall(ret))
    dcommon_raw = ""
    dcommon_path = os.path.join(inc, "dcommon.h")
    if os.path.isfile(dcommon_path):
        dcommon_raw = sp.load_header(dcommon_path)
    dcommon_types = {m.group(2) for m in
                     re.finditer(r"typedef\s+(enum|struct)\s+(DWRITE_\w+)", dcommon_raw)}
    defs, members = index_dwrite_definitions(dwrite_raw)
    needed_types, missing_types = collect_dwrite_types(
        defs, members, sorted(seed_types), external=dcommon_types)
    if missing_types:
        die("dwrite.h is missing definitions for: %s" % ", ".join(sorted(missing_types)))
    ordered_types = sorted(needed_types, key=lambda n: defs[n][0])

    dw_parts = [BANNER]
    dw_parts.append(
        "#ifndef MONAC_PLATFORM_DWRITE_C_H\n#define MONAC_PLATFORM_DWRITE_C_H\n\n")
    dw_parts.append('#include "com_base.h"\n')
    dw_parts.append('#include "iids_gen.h"\n')
    dw_parts.append("\n#ifndef MC_SKIP_DWRITE_TYPES\n")
    dw_parts.append("#include <dcommon.h>\n")
    for name in ordered_types:
        dw_parts.append("\n" + apply_aliases(defs[name][2].strip(), name) + "\n")
    dw_parts.append(
        "\nHRESULT WINAPI DWriteCreateFactory(DWRITE_FACTORY_TYPE factoryType,\n"
        "                                   REFIID iid, MC_IUnknown **factory);\n")
    dw_parts.append("#endif /* MC_SKIP_DWRITE_TYPES */\n")
    dw_parts.append("\n" + forward_decls(order_dw) + "\n")
    dw_parts.append("\n" + object_structs(order_dw) + "\n")
    for name in order_dw:
        text, _pairs = emit_interface(
            name, dwrite_tables[name],
            lambda i, m: m in DWRITE_TYPED, owned)
        dw_parts.append("\n" + text + "\n")
    dw_parts.append("\n#endif /* MONAC_PLATFORM_DWRITE_C_H */\n")
    dwrite_text = "".join(dw_parts)

    # ---- iids_gen.h ----------------------------------------------------
    guids = {}
    guids.update(index_guids(d2d_raw))
    guids.update(index_guids(dwrite_raw))
    for header, names in EXTRA_GUID_SOURCES:
        header_path = os.path.join(inc, header)
        if not os.path.isfile(header_path):
            die("missing %s" % header)
        found = index_guids(sp.load_header(header_path))
        for name in names:
            if name not in found:
                die("%s has no DEFINE_GUID for %s" % (header, name))
            guids[name] = found[name]
    wanted = set()
    for name in owned_d2d | owned_dwrite:
        wanted.add("IID_" + name)
    wanted.discard("IID_IUnknown")
    for _header, names in EXTRA_GUID_SOURCES:
        wanted |= set(names)
    iid_parts = [BANNER]
    iid_parts.append(
        "#ifndef MONAC_PLATFORM_IIDS_GEN_H\n#define MONAC_PLATFORM_IIDS_GEN_H\n\n")
    iid_missing = []
    for name in sorted(wanted):
        value = guids.get(name)
        if value is None:
            iid_missing.append(name)
            continue
        iid_parts.append("DEFINE_GUID(%s, %s);\n" % (name, value))
    if iid_missing:
        warn("no DEFINE_GUID available for: %s" % ", ".join(iid_missing))
    iid_parts.append("\n#endif /* MONAC_PLATFORM_IIDS_GEN_H */\n")
    iids_text = "".join(iid_parts)

    # ---- tests/shim_layout_checks.h ------------------------------------
    blocks_all = {}
    blocks_all.update(blocks_d2d)
    blocks_all.update(blocks_dw)
    chk = [BANNER]
    chk.append("#include <stddef.h>\n")
    for name in sp.SEED_D2D + sp.SEED_DWRITE:
        if name == "IUnknown":
            continue
        flat = d2d_tables.get(name) or dwrite_tables.get(name)
        _base, own = sp.parse_vtbl(name, blocks_all[name], warn)
        _text, pairs = emit_interface(name, flat, lambda i, m: True, owned)
        seen = set()
        unique_own = []
        for mname, field in pairs[len(flat) - len(own):]:
            if mname in seen:
                continue
            seen.add(mname)
            unique_own.append((mname, field))
        chk.append("\n/* %s: %d slots */\n" % (name, len(flat)))
        chk.append(
            '_Static_assert(sizeof(MC_%sVtbl) == sizeof(%sVtbl), "%s vtable size");\n'
            % (name, name, name))
        for mname, field in unique_own:
            chk.append(
                '_Static_assert(offsetof(MC_%sVtbl, %s) == offsetof(%sVtbl, %s), "%s::%s offset");\n'
                % (name, field, name, mname, name, mname))
    checks_text = "".join(chk)

    # ---- tools/shim_manifest.txt ---------------------------------------
    man = []
    for name in sp.SEED_D2D + sp.SEED_DWRITE:
        tbl = d2d_tables.get(name) or dwrite_tables.get(name)
        man.append("%s %d" % (name, len(tbl)))
        for _ret, mname, _args, _s in tbl:
            man.append("  " + mname)
    manifest = "\n".join(man) + "\n"

    outputs = {
        os.path.join(ROOT, "src", "platform", "d2d_c.h"): d2d_text,
        os.path.join(ROOT, "src", "platform", "dwrite_c.h"): dwrite_text,
        os.path.join(ROOT, "src", "platform", "iids_gen.h"): iids_text,
        os.path.join(ROOT, "tools", "shim_manifest.txt"): manifest,
        os.path.join(ROOT, "tests", "shim_layout_checks.h"): checks_text,
    }

    dirty = []
    for path, text in outputs.items():
        old = None
        if os.path.isfile(path):
            with open(path, encoding="utf-8") as fh:
                old = fh.read()
        if old != text:
            dirty.append(path)
            if not args.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(text)
    if args.check:
        if dirty:
            for p in dirty:
                print("out of date: %s" % os.path.relpath(p, ROOT))
            sys.exit(1)
        print("shim headers up to date")
    else:
        for p in dirty:
            print("wrote %s" % os.path.relpath(p, ROOT))
        if not dirty:
            print("shim headers already up to date")


if __name__ == "__main__":
    main()
